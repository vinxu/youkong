// ========== 压缩时间模拟测试：画像定义 ==========

// SimPersona 模拟画像定义
type SimPersona struct {
	ID          string // "S01"-"S25"
	Name        string // "朝九晚六上班族"
	Description string

	// 用户画像（注入 V3InferenceContext.Profile）
	OccupationType model.OccupationType
	WorkSchedule   model.WorkSchedule
	LifestyleType  model.LifestyleType
	City           string

	// 每日行为模板
	WeekdaySlots []SimTimeSlot // 工作日
	WeekendSlots []SimTimeSlot // 周末

	// 典型时刻表（注入 TodaySchedule）
	WeekdaySchedule []model.ScheduleItem
	WeekendSchedule []model.ScheduleItem
}

// SimTimeSlot 时间窗口 + 传感器模板 + 期望推断
type SimTimeSlot struct {
	StartHour int // 0-23
	EndHour   int // 0-23

	// 传感器模板
	Screen     *model.ScreenData
	Location   *model.LocationData
	Movement   *model.MovementData
	Calendar   *model.CalendarData
	Battery    *model.BatteryData
	Mode       *model.ModeData
	Connection *model.ConnectionData

	// 期望推断（用于评分）
	ExpectedKeywords []string // activity 包含任一关键词 = pass
	ExpectedAvail    *bool    // 期望 is_available，nil = 不检查
}

